export function translate(locale, key, vars) {
  const dict = DICT[locale] || DICT.en;
  let value = key.split('.').reduce((acc, part) => (acc && acc[part] != null ? acc[part] : null), dict);
  if (value == null) {
    value = key.split('.').reduce((acc, part) => (acc && acc[part] != null ? acc[part] : null), DICT.en);
  }
  if (value == null) return key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) value = value.replaceAll(`{${k}}`, String(v));
  }
  return value;
}
